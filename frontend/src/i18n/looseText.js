export function translateLooseText(text, language) {
  if (typeof text !== 'string' || language === 'en') return text

  const exact = exactTranslations.get(text)?.[language]
  if (exact) return exact

  if (language === 'sw') {
    const swExact =
      swExactTranslations.get(text) ||
      swExactTranslations.get(text.replace(/\n/g, '\r\n')) ||
      swExactTranslations.get(text.replace(/\r\n/g, '\n'))
    if (swExact) return swExact
  }

  const phraseOutput = (tourPhraseReplacements[language] || [])
    .sort((a, b) => b[0].length - a[0].length)
    .reduce((output, [from, to]) => output.split(from).join(to), text)

  if (phraseOutput !== text) return phraseOutput

  const languageReplacements = [
    ...(expandedReplacements[language] || []),
    ...(replacements[language] || []),
  ].sort((a, b) => b[0].length - a[0].length)

  return languageReplacements.reduce(
    (output, [from, to]) => output.split(from).join(to),
    text,
  )
}
