export function translateText(text, language = 'pt') {
  if (typeof text !== 'string') return text
  const lang = normalizeLanguage(language)

  if (lang === 'pt') return toPortuguese(text)
  if (lang === 'en') return exact.en[text] || commonExact.en[text] || text

  let output =
    exact[lang]?.[text] || commonExact[lang]?.[text] || exact.en[text] || commonExact.en[text] || text
  ;(replacements[lang] || []).forEach(([from, to]) => {
    output = output.split(from).join(to)
  })

  if (isDev && lang !== DEFAULT_LANGUAGE && output === text) {
    const missingKey = `${lang}:${text}`
    if (!loggedMissingTranslations.has(missingKey)) {
      loggedMissingTranslations.add(missingKey)
      console.warn(`[i18n] Missing text translation for "${text}" in language "${lang}".`)
    }
  }

  return output
}
